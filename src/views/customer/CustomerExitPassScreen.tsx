import { useState, useEffect, useRef, useCallback, useMemo } from "react";
import { useNavigate, useParams } from "react-router-dom";
import { QRCodeSVG } from "qrcode.react";
import { useShopping } from "../../context/ShoppingContext";
import { useAuth } from "../../context/AuthContext";
import { getOrderById, createExitQRPayload } from "../../utils/orderStorage";
import { CustomerLayout } from "../../layouts/CustomerLayout";
import { fmt } from "../../utils/formatters";
import { IcBack, IcCheck, IcAlert, IcReceipt } from "../../components/common/Icons";
import { EmptyState } from "../../components/common/EmptyState";
import { isSupabaseConfigured } from "../../lib/supabase";
import {
  fetchCustomerOrderLive,
  LiveExitPass,
} from "../../services/customerOrderService";
import { CompletedOrder } from "../../types";

export function CustomerExitPassScreen() {
  const navigate = useNavigate();
  const { orderId: paramOrderId } = useParams<{ orderId?: string }>();
  const { completedOrder, selectedHistoryOrder } = useShopping();
  const { user } = useAuth();

  // 1. Initial resolution of order ID
  const targetOrderId = useMemo(() => {
    if (paramOrderId) return paramOrderId.trim();
    if (completedOrder?.orderId) return completedOrder.orderId.trim();
    if (selectedHistoryOrder?.orderId) return selectedHistoryOrder.orderId.trim();
    return null;
  }, [paramOrderId, completedOrder, selectedHistoryOrder]);

  // 2. Component state
  const [order, setOrder] = useState<CompletedOrder | null>(() => {
    if (targetOrderId) {
      const local = getOrderById(targetOrderId);
      if (local) return local;
    }
    if (completedOrder) return completedOrder;
    if (selectedHistoryOrder) return selectedHistoryOrder;
    return null;
  });

  const [exitPass, setExitPass] = useState<LiveExitPass | null>(null);
  const [isExitPassValid, setIsExitPassValid] = useState<boolean>(false);
  const [isPending, setIsPending] = useState<boolean>(() => {
    const initialStatus = order?.paymentStatus || "PENDING";
    return initialStatus === "PENDING";
  });
  const [isRetrievingPass, setIsRetrievingPass] = useState<boolean>(false);
  const [isSyncing, setIsSyncing] = useState<boolean>(false);
  const [syncError, setSyncError] = useState<string | null>(null);
  const [isForbidden, setIsForbidden] = useState<boolean>(false);
  const [isNotFound, setIsNotFound] = useState<boolean>(false);
  const [lastSyncedAt, setLastSyncedAt] = useState<string | null>(null);

  // Ref lock to prevent overlapping in-flight sync requests
  const isFetchingRef = useRef<boolean>(false);
  const pollTimerRef = useRef<ReturnType<typeof setInterval> | null>(null);

  /**
   * Authoritative Live Order & Exit Pass Synchronizer
   */
  const syncOrderAndPass = useCallback(
    async (isManualRetry: boolean = false) => {
      if (!targetOrderId) return;
      if (isFetchingRef.current) return;

      isFetchingRef.current = true;
      if (isManualRetry) {
        setIsSyncing(true);
        setSyncError(null);
      }

      try {
        const result = await fetchCustomerOrderLive(targetOrderId, user?.id);

        if (result.forbidden) {
          setIsForbidden(true);
          setSyncError("Access Denied: You do not have permission to view this customer order.");
          if (pollTimerRef.current) {
            clearInterval(pollTimerRef.current);
            pollTimerRef.current = null;
          }
          return;
        }

        if (result.notFound) {
          setIsNotFound(true);
          setSyncError(`Order '${targetOrderId}' was not found in the store database.`);
          if (pollTimerRef.current) {
            clearInterval(pollTimerRef.current);
            pollTimerRef.current = null;
          }
          return;
        }

        if (!result.success) {
          setSyncError(result.error || "Could not refresh order status from store database.");
          return;
        }

        // Successfully fetched authoritative database state
        setSyncError(null);
        setLastSyncedAt(new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit", second: "2-digit" }));

        if (result.order) {
          setOrder(result.order);
        }

        setIsPending(result.isPending);

        if (result.isConfirmed) {
          if (result.exitPass && result.isExitPassValid) {
            setExitPass(result.exitPass);
            setIsExitPassValid(true);
            setIsRetrievingPass(false);

            // Confirmed and pass retrieved: stop polling
            if (pollTimerRef.current) {
              clearInterval(pollTimerRef.current);
              pollTimerRef.current = null;
            }
          } else {
            // Confirmed, but pass is still being generated by database trigger
            setIsRetrievingPass(true);
            setIsExitPassValid(false);
          }
        } else {
          setIsRetrievingPass(false);
          setIsExitPassValid(false);
        }

        // If order reached terminal failed/refunded state, stop polling
        if (result.isTerminal && !result.isConfirmed) {
          if (pollTimerRef.current) {
            clearInterval(pollTimerRef.current);
            pollTimerRef.current = null;
          }
        }
      } catch (err: unknown) {
        const msg = err instanceof Error ? err.message : "Error syncing order";
        setSyncError(msg);
      } finally {
        isFetchingRef.current = false;
        setIsSyncing(false);
      }
    },
    [targetOrderId, user?.id]
  );

  // Initial fetch and 5-second polling setup
  useEffect(() => {
    if (!targetOrderId) return;

    let isMounted = true;

    // Initial fetch
    syncOrderAndPass(false);

    // Setup 5-second polling while order is pending or pass is being generated
    if (isSupabaseConfigured) {
      pollTimerRef.current = setInterval(() => {
        if (!isMounted) return;
        syncOrderAndPass(false);
      }, 5000);
    }

    return () => {
      isMounted = false;
      if (pollTimerRef.current) {
        clearInterval(pollTimerRef.current);
        pollTimerRef.current = null;
      }
    };
  }, [targetOrderId, syncOrderAndPass]);

  // Compute formatted issue time
  const issueDisplay = useMemo(() => {
    const rawTime = exitPass?.issuedAt || order?.issuedAt || order?.paidAt;
    if (rawTime) {
      try {
        const d = new Date(rawTime);
        return d.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
      } catch {
        return "Just now";
      }
    }
    return "Pending Confirmation";
  }, [exitPass?.issuedAt, order?.issuedAt, order?.paidAt]);

  // Compute formatted expiry time
  const expiryDisplay = useMemo(() => {
    const rawExpiry = exitPass?.expiresAt || order?.mockExpiry;
    if (rawExpiry) {
      try {
        const d = new Date(rawExpiry);
        return d.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
      } catch {
        return "1 hour from payment";
      }
    }
    return "Valid for 60 mins";
  }, [exitPass?.expiresAt, order?.mockExpiry]);

  // Resolve QR code payload strictly from authoritative database pass
  const finalQrPayload = useMemo(() => {
    if (isExitPassValid && exitPass?.qrPayload) {
      return exitPass.qrPayload;
    }
    // Only in offline prototype mode when Supabase is unconfigured and local order is confirmed
    if (!isSupabaseConfigured && order && order.paymentStatus === "CONFIRMED") {
      return createExitQRPayload(order);
    }
    return "";
  }, [isExitPassValid, exitPass?.qrPayload, order]);

  // Forbidden / Unauthorized Guard
  if (isForbidden) {
    return (
      <CustomerLayout showHeader={true} showFooter={true} onBack={() => navigate("/history")}>
        <div className="flex flex-1 flex-col items-center justify-center p-6 text-center max-w-[440px] mx-auto w-full">
          <EmptyState
            emoji="⛔"
            title="Access Denied"
            description="You do not have permission to view or unlock the exit pass for this order."
            action={{
              label: "Return to Order History",
              onClick: () => navigate("/history"),
            }}
          />
        </div>
      </CustomerLayout>
    );
  }

  // Not Found State
  if (isNotFound || (!order && !isSyncing)) {
    return (
      <CustomerLayout showHeader={true} showFooter={true} onBack={() => navigate("/shop")}>
        <div className="flex flex-1 flex-col items-center justify-center p-6 text-center max-w-[440px] mx-auto w-full">
          <EmptyState
            emoji="⚠️"
            title="No Active Exit Pass"
            description="An exit pass can only be generated after a self-checkout payment has been completed. Complete payment to obtain your security gate pass."
            action={{
              label: "Go to Cart",
              onClick: () => navigate("/shop"),
            }}
            secondaryAction={{
              label: "Order History",
              onClick: () => navigate("/history"),
            }}
          />
        </div>
      </CustomerLayout>
    );
  }

  return (
    <CustomerLayout
      showHeader={true}
      showFooter={true}
      maxWidthClass="max-w-[480px]"
      onBack={() => navigate(order?.orderId ? `/receipt/${order.orderId}` : "/shop")}
      backLabel="Back to Receipt"
    >
      <div className="flex flex-1 flex-col qless-fade-in pb-12 w-full space-y-4">
        {/* Top Header */}
        <div className="flex items-center justify-between border-b border-slate-200/80 pb-3">
          <button
            onClick={() => navigate(order?.orderId ? `/receipt/${order.orderId}` : "/shop")}
            className="flex items-center gap-1.5 text-xs font-semibold text-[#667085] transition hover:text-[#101828]"
          >
            <IcBack />
            <span>Digital Receipt</span>
          </button>

          {isPending ? (
            <span className="inline-flex items-center gap-1.5 rounded-full bg-amber-50 border border-amber-200 px-3 py-1 text-xs font-bold text-amber-800 shadow-2xs">
              <span className="h-2 w-2 rounded-full bg-amber-500 animate-pulse" />
              <span>Pass Locked · Payment Pending</span>
            </span>
          ) : isRetrievingPass ? (
            <span className="inline-flex items-center gap-1.5 rounded-full bg-blue-50 border border-blue-200 px-3 py-1 text-xs font-bold text-blue-800 shadow-2xs">
              <span className="h-2 w-2 rounded-full bg-blue-500 animate-pulse" />
              <span>Payment Confirmed · Issuing Gate Pass</span>
            </span>
          ) : (
            <span className="inline-flex items-center gap-1.5 rounded-full bg-emerald-50 border border-emerald-200 px-3 py-1 text-xs font-bold text-[#16A36A] shadow-2xs">
              <span className="h-2 w-2 rounded-full bg-[#16A36A] animate-pulse" />
              <span>Pass Active · Ready for Turnstile Gate</span>
            </span>
          )}
        </div>

        {/* Sync Error Banner with Retry */}
        {syncError && (
          <div
            role="alert"
            className="rounded-2xl border border-red-200 bg-red-50 p-3.5 text-xs text-red-800 flex items-start justify-between gap-3 qless-scale-in"
          >
            <div className="flex items-start gap-2 min-w-0">
              <span className="mt-0.5 text-red-600 shrink-0">
                <IcAlert />
              </span>
              <div>
                <p className="font-bold">Sync Error</p>
                <p className="text-[11px] text-red-700 leading-snug mt-0.5">{syncError}</p>
              </div>
            </div>
            <button
              type="button"
              onClick={() => syncOrderAndPass(true)}
              className="rounded-lg bg-red-700 px-3 py-1.5 text-[11px] font-bold text-white shrink-0 hover:bg-red-800 active:scale-95 transition cursor-pointer"
            >
              Retry Sync
            </button>
          </div>
        )}

        {/* Customer Exit Pass Card */}
        <div className="rounded-3xl border border-slate-200/80 bg-white p-6 sm:p-7 shadow-xs text-center space-y-5">
          {/* Store Identification */}
          <div>
            <div className="flex items-center justify-center gap-2">
              <span
                className="inline-block h-2.5 w-2.5 rounded-full"
                style={{ backgroundColor: order?.store?.brandColor || "#16A36A" }}
              />
              <h2 className="font-poppins text-lg font-bold text-[#101828]">
                {order?.store?.name || "QLess Mart"}
              </h2>
            </div>
            <p className="text-xs text-[#667085]">
              {order?.store?.branch || "Self-Checkout"} · Automated Gate Pass
            </p>
          </div>

          {/* QR Code / Locked Pass State / Issuing State */}
          {isPending ? (
            /* STATE A: PAYMENT PENDING (LOCKED) */
            <div className="mx-auto flex flex-col items-center justify-center rounded-2xl border-2 border-dashed border-amber-300 bg-amber-50/70 p-6 max-w-[300px] shadow-inner text-center">
              <div className="h-16 w-16 rounded-2xl bg-amber-100 border border-amber-200 flex items-center justify-center text-3xl shadow-xs">
                🔒
              </div>
              <h3 className="mt-3 font-poppins text-sm font-bold text-[#101828]">
                Exit Gate Pass Locked
              </h3>
              <p className="mt-1 text-xs text-amber-900 leading-relaxed font-medium">
                Payment pending — please complete payment at the cashier counter.
              </p>
              <p className="mt-1 text-[11px] text-amber-800 leading-snug">
                Your exit pass will remain locked until an authorized cashier confirms receipt of cash for this order.
              </p>

              {/* Order Reference Box */}
              <div className="mt-4 rounded-xl bg-white px-4 py-2.5 border border-amber-200 shadow-2xs w-full">
                <span className="text-[10px] font-bold text-[#667085] uppercase tracking-wider block">
                  Order Reference for Cashier
                </span>
                <span className="font-mono text-sm font-bold text-[#101828] select-all">
                  {order?.orderId}
                </span>
              </div>

              {/* Polling Liveness Indicator */}
              <div className="mt-3 flex items-center justify-center gap-2 text-[10.5px] text-amber-800">
                <span className="h-2 w-2 rounded-full bg-amber-600 animate-pulse" />
                <span>Checking cashier payment… (Auto-sync 5s)</span>
              </div>

              <button
                type="button"
                onClick={() => syncOrderAndPass(true)}
                disabled={isSyncing}
                className="mt-2.5 text-[11px] font-bold text-amber-900 underline hover:text-amber-950 disabled:opacity-50 cursor-pointer"
              >
                {isSyncing ? "Checking database…" : "Refresh Status Now"}
              </button>
            </div>
          ) : isRetrievingPass ? (
            /* STATE B: PAYMENT CONFIRMED — RETRIEVING PASS */
            <div className="mx-auto flex flex-col items-center justify-center rounded-2xl border-2 border-dashed border-blue-300 bg-blue-50/70 p-6 max-w-[300px] shadow-inner text-center">
              <div className="h-14 w-14 rounded-2xl bg-blue-100 border border-blue-200 flex items-center justify-center text-2xl shadow-xs">
                <svg className="h-7 w-7 animate-spin text-blue-700" viewBox="0 0 24 24" fill="none">
                  <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="3" />
                  <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8v4l3-3-3-3v4a8 8 0 00-8 8h4z" />
                </svg>
              </div>
              <h3 className="mt-3 font-poppins text-sm font-bold text-blue-950">
                Payment Confirmed
              </h3>
              <p className="mt-1 text-xs text-blue-900 leading-snug font-medium">
                Payment confirmed — retrieving your exit pass.
              </p>
              <p className="mt-1 text-[11px] text-blue-800 leading-snug">
                The database turnstile trigger has registered confirmation. Generating your secure QR credentials…
              </p>
            </div>
          ) : isExitPassValid && finalQrPayload ? (
            /* STATE C: CONFIRMED & VALID DATABASE EXIT QR */
            <div className="mx-auto flex flex-col items-center justify-center rounded-2xl border-2 border-dashed border-emerald-300 bg-emerald-50/40 p-4 sm:p-5 max-w-[280px] shadow-inner qless-scale-in">
              <div className="bg-white p-3 rounded-2xl shadow-sm border border-slate-200/80">
                <QRCodeSVG
                  value={finalQrPayload}
                  size={190}
                  level="M"
                  includeMargin={false}
                  fgColor="#101828"
                />
              </div>

              <div className="mt-3 flex items-center gap-1.5 text-[#16A36A] font-bold text-xs">
                <IcCheck />
                <span>Turnstile Gate Pass Active</span>
              </div>

              <p className="mt-1 font-mono text-[11px] font-bold text-[#101828] tracking-wider select-all">
                {order?.orderId}
              </p>
              <p className="text-[10.5px] text-[#667085] mt-0.5">
                Present screen face-up to the turnstile sensor
              </p>
            </div>
          ) : (
            /* STATE D: UNEXPECTED / PASS EXPIRED OR REVOKED */
            <div className="mx-auto flex flex-col items-center justify-center rounded-2xl border-2 border-dashed border-red-300 bg-red-50/70 p-6 max-w-[300px] shadow-inner text-center">
              <span className="text-3xl">⚠️</span>
              <h3 className="mt-2 font-poppins text-sm font-bold text-red-900">
                Exit Pass Unavailable
              </h3>
              <p className="mt-1 text-xs text-red-800 leading-snug">
                {exitPass?.status === "EXPIRED"
                  ? "This exit pass has expired. Please speak with the customer service desk."
                  : exitPass?.status === "REVOKED"
                  ? "This pass has been revoked by store security."
                  : "Unable to retrieve a valid exit pass for this order."}
              </p>
              <button
                type="button"
                onClick={() => syncOrderAndPass(true)}
                className="mt-3 rounded-xl bg-red-700 px-3 py-1.5 text-xs font-bold text-white hover:bg-red-800 transition cursor-pointer"
              >
                Retry Fetch
              </button>
            </div>
          )}

          {/* Pass Details Breakdown */}
          <div className="rounded-2xl border border-slate-100 bg-slate-50/80 p-4 text-xs text-left grid grid-cols-2 gap-3">
            <div>
              <p className="text-[10px] font-bold uppercase tracking-wider text-[#667085]">
                Item Count
              </p>
              <p className="font-bold text-[#101828]">{order?.itemCount ?? 0} items</p>
            </div>
            <div>
              <p className="text-[10px] font-bold uppercase tracking-wider text-[#667085]">
                {isPending ? "Amount Due" : "Amount Paid"}
              </p>
              <p className={`font-bold ${isPending ? "text-amber-700" : "text-[#16A36A]"}`}>
                {fmt(order?.finalTotal ?? 0)}
              </p>
            </div>
            <div>
              <p className="text-[10px] font-bold uppercase tracking-wider text-[#667085]">
                Pass Issued At
              </p>
              <p className="font-semibold text-[#101828]">
                {isPending ? "Pending Payment" : issueDisplay}
              </p>
            </div>
            <div>
              <p className="text-[10px] font-bold uppercase tracking-wider text-[#667085]">
                Pass Valid Until
              </p>
              <p className="font-semibold text-[#101828]">
                {isPending ? "Pending Payment" : expiryDisplay}
              </p>
            </div>
            <div className="col-span-2 flex items-center justify-between border-t border-slate-200/60 pt-2.5">
              <span className="text-[10px] font-bold uppercase tracking-wider text-[#667085]">
                Payment Status
              </span>
              <span className={`font-bold ${isPending ? "text-amber-700" : "text-[#16A36A]"}`}>
                {isPending
                  ? (order?.paymentMethod === "cash"
                      ? "Pending Cashier Payment"
                      : "Pending Gateway Confirmation")
                  : "Confirmed (Database Verified)"}
              </span>
            </div>
          </div>

          {/* Authoritative Security Gate Notice */}
          {isPending ? (
            <div className="rounded-2xl border border-amber-200 bg-amber-50/90 p-3.5 text-[11px] text-amber-900 text-left leading-relaxed">
              <p className="font-bold flex items-center gap-1.5">
                <span>🛡️</span> Turnstile Gate Protection Active
              </p>
              <p className="mt-0.5 text-amber-800 text-[10.5px]">
                Turnstiles and security officers strictly reject unconfirmed purchases. Your exit pass will unlock automatically once the cashier confirms receipt of cash.
              </p>
            </div>
          ) : (
            <div className="rounded-2xl border border-emerald-200 bg-emerald-50/80 p-3.5 text-[11px] text-emerald-900 text-left leading-relaxed">
              <p className="font-bold flex items-center gap-1.5">
                <span>🛡️</span> Database Verified Gate Clearance
              </p>
              <p className="mt-0.5 text-emerald-800 text-[10.5px]">
                This QR pass is linked to verified database order <strong className="font-mono">{order?.orderId}</strong> and valid until {expiryDisplay}. Scan face-up at the turnstile gate for departure.
              </p>
            </div>
          )}

          {lastSyncedAt && (
            <p className="text-[10px] text-[#667085]">
              Last verified with store database at {lastSyncedAt}
            </p>
          )}
        </div>

        {/* Action Controls */}
        <div className="mt-5 space-y-2.5">
          {/* Back to Receipt */}
          <button
            type="button"
            onClick={() => navigate(order?.orderId ? `/receipt/${order.orderId}` : "/shop")}
            className="flex h-12 w-full items-center justify-center gap-2 rounded-xl bg-[#101828] font-poppins text-xs font-semibold text-white shadow-sm transition hover:bg-slate-800 active:scale-98 cursor-pointer"
          >
            <IcReceipt />
            <span>View Full Itemised Receipt</span>
          </button>

          {/* Shopping History Link */}
          <button
            type="button"
            onClick={() => navigate("/history")}
            className="flex h-10 w-full items-center justify-center text-xs font-semibold text-[#667085] hover:text-[#101828] hover:underline transition cursor-pointer"
          >
            View All Order History
          </button>
        </div>
      </div>
    </CustomerLayout>
  );
}
